import { useState } from 'react';
import { api } from '../api';
import { Notice, Tag, useLoad } from '../components';
import { TYPE_LABEL, type Item } from '../types';

export default function ItemBank() {
  const [status, setStatus] = useState('');
  const [items, error, reload] = useLoad(() => api<Item[]>(`/api/items${status ? `?status=${status}` : ''}`), [status]);
  return (
    <div>
      <h1>Item bank</h1>
      <div className="filters">
        <div className="segmented">
          {[['', 'All'], ['DRAFT', 'Drafts to review'], ['APPROVED', 'Approved'], ['REJECTED', 'Rejected']].map(([v, l]) => (
            <button key={v} className={status === v ? 'active' : ''} onClick={() => setStatus(v)}>{l}</button>))}
        </div>
      </div>
      <Notice>{error}</Notice>
      <div className="stack">{items?.map((i) => <ItemCard key={i.id} item={i} onChange={reload} />)}</div>
      {items?.length === 0 && <p className="muted">No items.</p>}
    </div>
  );
}

export function ItemCard({ item, onChange, expanded = false }: { item: Item; onChange: () => void; expanded?: boolean }) {
  const [open, setOpen] = useState(expanded);
  const [note, setNote] = useState('');
  const [error, setError] = useState('');
  const review = item.review_notes?.agent_review;
  async function decide(decision: 'APPROVE' | 'REJECT') {
    try { await api(`/api/items/${item.id}/decision`, { method: 'POST', body: { decision, note } }); onChange(); }
    catch (e) { setError((e as Error).message); }
  }
  return (
    <article className="card item">
      <div className="row-between">
        <div className="tags">
          <Tag>{TYPE_LABEL[item.item_type]}</Tag><Tag>{item.difficulty.toLowerCase()}</Tag>
          <Tag tone="info">{item.standard_code}</Tag>
          <Tag tone={item.status === 'APPROVED' ? 'good' : item.status === 'DRAFT' ? 'warn' : 'bad'}>{item.status.toLowerCase()}</Tag>
          {item.source === 'AUTHORING_AGENT' && <Tag>AI-authored</Tag>}
        </div>
        <button className="link" onClick={() => setOpen(!open)}>{open ? 'Hide details' : 'Details'}</button>
      </div>
      <p className="stem">{item.stem}</p>
      {item.choices && <ol className="choices" type="A">{item.choices.map((c, i) => <li key={i}>{c}</li>)}</ol>}
      {open && (
        <div className="details">
          <h3>Answer key</h3><pre className="pre">{item.answer_key}</pre>
          <h3>Rubric</h3>
          <table className="compact"><tbody>{item.rubric.map((r) => (
            <tr key={r.criterion}><td><strong>{r.criterion}</strong></td><td className="num">{r.max_points} pt</td><td>{r.descriptors}</td></tr>))}</tbody></table>
          {item.tests && <><h3>Tests</h3><pre className="pre">{item.tests.map((t) => `solve(${JSON.stringify(t.args).slice(1, -1)}) == ${JSON.stringify(t.expected)}`).join('\n')}</pre></>}
          {review && (
            <><h3>Agent self-review</h3>
              <p>Quality {review.overall_quality}/5{review.issues.length > 0 && <> · {review.issues.join('; ')}</>}</p>
              {item.review_notes?.served_by && <p className="muted small">Generated by {item.review_notes.served_by}</p>}</>
          )}
        </div>
      )}
      {item.status === 'DRAFT' && (
        <div className="decide">
          <input placeholder="Note (optional)" value={note} onChange={(e) => setNote(e.target.value)} />
          <button onClick={() => decide('APPROVE')}>Approve</button>
          <button className="secondary" onClick={() => decide('REJECT')}>Reject</button>
        </div>
      )}
      <Notice>{error}</Notice>
    </article>
  );
}
